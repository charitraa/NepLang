/* Build-time helper: joins the runtime sources (headers first, then .c files) into one
 * C translation unit and writes it as a byte array, so `neplang build` can compile native
 * programs without a runtime folder on disk.
 *
 *   embed_runtime OUT.c FILE...
 *
 * Local `#include "..."` lines are dropped (every header is already inlined, in order) and
 * any `#define _POSIX_C_SOURCE` is moved to the very top, before the first system include.
 * A byte array is used instead of a string literal: -Wpedantic rejects literals > 4095 chars.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *skip_space(const char *s) {
    while (*s == ' ' || *s == '\t') s++;
    return s;
}

/* "#include \"x\"" or "#define _POSIX_C_SOURCE ..." (any spacing after '#') */
static int is_directive(const char *line, const char *name, const char *arg_prefix) {
    const char *p = skip_space(line);
    if (*p != '#') return 0;
    p = skip_space(p + 1);
    size_t n = strlen(name);
    if (strncmp(p, name, n) != 0) return 0;
    p = skip_space(p + n);
    return strncmp(p, arg_prefix, strlen(arg_prefix)) == 0;
}

static unsigned long column;
static unsigned long total;

static void emit_bytes(FILE *out, const char *s, size_t n) {
    for (size_t i = 0; i < n; i++) {
        fprintf(out, "%u,", (unsigned)(unsigned char)s[i]);
        if (++column == 24) {
            fputc('\n', out);
            column = 0;
        }
    }
    total += n;
}

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: %s OUT.c FILE...\n", argv[0]);
        return 1;
    }
    FILE *out = fopen(argv[1], "w");
    if (!out) {
        fprintf(stderr, "embed_runtime: can't write '%s'\n", argv[1]);
        return 1;
    }
    fprintf(out, "/* Generated by tools/embed_runtime.c from the runtime sources. Do not edit. */\n"
                 "const unsigned char neplang_runtime_source[] = {\n");

    const char *posix = "#define _POSIX_C_SOURCE 200809L\n";
    emit_bytes(out, posix, strlen(posix));

    char line[4096];
    for (int i = 2; i < argc; i++) {
        FILE *in = fopen(argv[i], "r");
        if (!in) {
            fprintf(stderr, "embed_runtime: can't read '%s'\n", argv[i]);
            fclose(out);
            remove(argv[1]);
            return 1;
        }
        char header[600];
        snprintf(header, sizeof header, "/* ---- %s ---- */\n", argv[i]);
        emit_bytes(out, header, strlen(header));
        while (fgets(line, sizeof line, in)) {
            if (is_directive(line, "include", "\"") || is_directive(line, "define", "_POSIX_C_SOURCE")) continue;
            size_t n = strlen(line);
            if (n >= 2 && line[n - 2] == '\r') {   /* CRLF checkouts on Windows */
                line[n - 2] = '\n';
                n--;
            }
            emit_bytes(out, line, n);
        }
        fclose(in);
    }
    fprintf(out, "0};\nconst unsigned long neplang_runtime_source_size = %luUL;\n", total);
    if (fclose(out) != 0) {
        remove(argv[1]);
        return 1;
    }
    return 0;
}
